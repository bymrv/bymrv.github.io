const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)');
const jumpButton = document.querySelector('.page-jump');
let currentLanguage = 'es';
let atBottom = false;
let scrollFrame = 0;

function updateJumpButton() {
  scrollFrame = 0;
  const maxScroll = Math.max(0, document.documentElement.scrollHeight - window.innerHeight);
  atBottom = maxScroll - window.scrollY < 80;
  jumpButton.hidden = maxScroll < 100;
  jumpButton.classList.toggle('is-up', atBottom);
  const label = translations[currentLanguage][atBottom ? 'scroll-up' : 'scroll-down'];
  jumpButton.setAttribute('aria-label', label);
  jumpButton.title = label;
  jumpButton.querySelector('.jump-label').textContent = label;
}

function scheduleScrollUpdate() {
  if (!scrollFrame) scrollFrame = window.requestAnimationFrame(updateJumpButton);
}

function setLanguage(language, save = false) {
  const keepAtBottom = document.documentElement.scrollHeight - window.innerHeight - window.scrollY < 80;
  currentLanguage = Object.hasOwn(translations, language) ? language : 'es';
  const copy = translations[currentLanguage];
  document.documentElement.lang = currentLanguage;
  document.querySelectorAll('[data-i18n]').forEach(element => {
    const value = copy[element.dataset.i18n];
    if (value !== undefined) element.textContent = value;
  });
  for (const [suffix, attribute] of [['aria', 'aria-label'], ['alt', 'alt'], ['content', 'content']]) {
    document.querySelectorAll(`[data-i18n-${suffix}]`).forEach(element => {
      const value = copy[element.getAttribute(`data-i18n-${suffix}`)];
      if (value !== undefined) element.setAttribute(attribute, value);
    });
  }
  document.querySelectorAll('[data-language]').forEach(button => {
    button.setAttribute('aria-pressed', String(button.dataset.language === currentLanguage));
  });
  if (keepAtBottom) window.scrollTo({ top: document.documentElement.scrollHeight, behavior: 'instant' });
  updateJumpButton();
  if (save) {
    try { localStorage.setItem('portfolio-language', currentLanguage); } catch {}
  }
}

document.querySelectorAll('[data-language]').forEach(button => {
  button.addEventListener('click', () => setLanguage(button.dataset.language, true));
});

