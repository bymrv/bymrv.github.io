document.querySelectorAll('.project-card').forEach(card => {
  const spark = card.querySelector('.project-spark');
  if (!spark) return;
  let frame = 0;
  let startTime = null;
  let segments = [];
  let duration = 0;
  let width = 0;
  let height = 0;
  let pointerInside = false;

  function createPath() {
    const style = getComputedStyle(card);
    const bounds = card.getBoundingClientRect();
    const border = parseFloat(style.borderLeftWidth) || 0;
    const halfBorder = border / 2;
    const left = -halfBorder;
    const top = -halfBorder;
    const right = bounds.width - border - halfBorder;
    const bottom = bounds.height - border - halfBorder;
    const radius = Math.max(0, Math.min(parseFloat(style.borderTopLeftRadius) - halfBorder, (right - left) / 2, (bottom - top) / 2));

    function line(x1, y1, x2, y2, speed) {
      return {
        duration: Math.hypot(x2 - x1, y2 - y1) / speed,
        point(progress) { return { x: x1 + (x2 - x1) * progress, y: y1 + (y2 - y1) * progress }; }
      };
    }

    function arc(x, y, from, to) {
      return {
        duration: radius * Math.abs(to - from) / 220,
        point(progress) {
          const angle = from + (to - from) * progress;
          return { x: x + radius * Math.cos(angle), y: y + radius * Math.sin(angle) };
        }
      };
    }

    width = bounds.width;
    height = bounds.height;
    segments = [
      line(left + radius, top, right - radius, top, 430),
      arc(right - radius, top + radius, -Math.PI / 2, 0),
      line(right, top + radius, right, bottom - radius, 220),
      arc(right - radius, bottom - radius, 0, Math.PI / 2),
      line(right - radius, bottom, left + radius, bottom, 430),
      arc(left + radius, bottom - radius, Math.PI / 2, Math.PI),
      line(left, bottom - radius, left, top + radius, 220),
      arc(left + radius, top + radius, Math.PI, Math.PI * 1.5)
    ].filter(segment => segment.duration > 0);
    duration = segments.reduce((total, segment) => total + segment.duration, 0);
  }

  function positionSpark(elapsed) {
    let remaining = elapsed % duration;
    for (const segment of segments) {
      if (remaining <= segment.duration) {
        const point = segment.point(remaining / segment.duration);
        spark.style.transform = `translate3d(${point.x - spark.offsetWidth / 2}px, ${point.y - spark.offsetHeight / 2}px, 0)`;
        return;
      }
      remaining -= segment.duration;
    }
  }

  function shouldAnimate() {
    return !document.hidden && (pointerInside || !!card.querySelector(':focus-visible'));
  }

  function stop() {
    cancelAnimationFrame(frame);
    frame = 0;
    startTime = null;
    card.classList.remove('is-sparking');
  }

  function animate(timestamp) {
    if (!shouldAnimate()) { stop(); return; }
    if (startTime === null) startTime = timestamp;
    const bounds = card.getBoundingClientRect();
    if (bounds.width !== width || bounds.height !== height) createPath();
    if (duration > 0) positionSpark((timestamp - startTime) / 1000);
    frame = requestAnimationFrame(animate);
  }

  function refresh() {
    if (!shouldAnimate()) { stop(); return; }
    if (frame) return;
    createPath();
    if (!duration) return;
    positionSpark(0);
    card.classList.add('is-sparking');
    frame = requestAnimationFrame(animate);
  }

  card.addEventListener('pointerenter', event => {
    pointerInside = event.pointerType !== 'touch';
    refresh();
  });
  card.addEventListener('pointerleave', () => { pointerInside = false; refresh(); });
  card.addEventListener('pointercancel', () => { pointerInside = false; refresh(); });
  card.addEventListener('focusin', () => requestAnimationFrame(refresh));
  card.addEventListener('focusout', () => requestAnimationFrame(refresh));
  document.addEventListener('visibilitychange', refresh);
  pointerInside = matchMedia('(hover: hover)').matches && card.matches(':hover');
  refresh();
});
